def label(text):
    if not CJK.search(text):return text
    result=text
    for zh,en in sorted(PLOT.items(),key=lambda x:-len(x[0])):
        result=result.replace(zh,en)
    result=result.replace('，',', ').replace('−','−')
    if CJK.search(result):raise ValueError('Untranslated figure label: '+repr(text))
    return result

def wrapped_feature(text):
    return text.replace('Hallucinatory and delusional symptoms','Hallucinatory and\ndelusional symptoms')

