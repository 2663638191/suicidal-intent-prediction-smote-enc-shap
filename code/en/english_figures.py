def waterfalls(output,values,base,names,choice,X,text_audit):
    fig,axes=plt.subplots(2,1,figsize=(7.4,7.2))
    for ax,case,letter,title in zip(axes,choice,'ab',['Predicted-positive record','Predicted-negative record']):
        phi=values[case];top=np.argsort(np.abs(phi))[::-1][:5]
        other=[j for j in range(len(phi)) if j not in top]
        contributions=np.r_[phi[other].sum(),phi[top[::-1]]]
        labels=['Other features']
        for j in top[::-1]:
            raw=X.iloc[case][names[j]]
            raw_text=f'{raw:.2f}' if names[j] in original.连续变量 and pd.notna(raw) else TEXT.get(str(raw),str(raw))
            labels.append(wrapped_feature(FEATURES[names[j]])+' = '+raw_text)
        current=float(base[case]);positions=[current]
        span=max(.1,float(np.ptp(np.r_[current,current+np.cumsum(contributions)])))
        for i,value in enumerate(contributions):
            end=current+value;direction=1 if value>=0 else -1
            head=min(abs(value)*.35,span*.045);shoulder=end-direction*head
            ax.add_patch(Polygon([(current,i-.29),(shoulder,i-.29),(end,i),(shoulder,i+.29),(current,i+.29)],
               closed=True,facecolor=original.正色 if value>=0 else original.负色,edgecolor='none',alpha=.95,zorder=2))
            ax.axhline(i,color='#e8e8e8',lw=.6,linestyle=':',zorder=0)
            if abs(value)<span*.15:
                ax.text(end+.025*span*direction,i,f'{value:+.2f}',ha='left' if value>=0 else 'right',va='center',
                    fontsize=8.5,color='#303030',bbox={'facecolor':'white','edgecolor':'none','pad':.5,'alpha':.9})
            else:ax.text(current+value/2,i,f'{value:+.2f}',ha='center',va='center',fontsize=8.5,color='white')
            if i<len(contributions)-1:ax.plot([end,end],[i+.29,i+.71],color='#d0d0d0',lw=.6,linestyle='--',zorder=1)
            current=end;positions.append(current)
        ax.axvline(base[case],color='#cccccc',lw=.65,linestyle=':',zorder=0)
        ax.axvline(current,color='#c7c7c7',lw=.65,linestyle='--',zorder=0)
        ax.set_yticks(range(6),labels,fontsize=8.2);ax.set_ylim(-1.3,6.05)
        low,high=min(positions),max(positions);pad=max(.8,(high-low)*.15)
        ax.set_xlim(low-pad,high+pad)
        ax.text(base[case],-.70,rf'$E[f(x)]={base[case]:.2f}$',ha='center',va='center',fontsize=9)
        ax.text(current,5.65,rf'$f(x)={current:.2f}$',ha='center',va='center',fontsize=9)
        ax.set_xlabel('Calibrated log-odds',fontsize=9)
        ax.text(0,1.025,f'({letter}) {title}',transform=ax.transAxes,fontsize=9,va='bottom')
        ax.spines[['left','right','top']].set_visible(False);ax.tick_params(axis='y',length=0);ax.tick_params(axis='x',length=3,pad=2,labelsize=8)
    fig.subplots_adjust(left=.40,right=.985,bottom=.065,top=.95,hspace=.44)
    save_english(fig,output,'图10_主模型SHAP瀑布图_前五变量',text_audit,Path(output)/'figures'/'manuscript'/'Figure_5_SHAP_waterfalls')

