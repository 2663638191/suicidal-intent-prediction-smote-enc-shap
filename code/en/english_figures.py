def save_english(fig, output, name, text_audit, extra_path=None):
    """Translate figure artists, then save text and geometry without refitting."""
    # Tick text is regenerated by its formatter on each draw. Replace the
    # formatter labels as well as the current Text artists.
    for ax in fig.axes:
        xticks,yticks=ax.get_xticks(),ax.get_yticks()
        xlabels=[label(t.get_text()) for t in ax.get_xticklabels()]
        ylabels=[label(t.get_text()) for t in ax.get_yticklabels()]
        if len(xticks)==len(xlabels):ax.set_xticks(xticks,xlabels)
        if len(yticks)==len(ylabels):ax.set_yticks(yticks,ylabels)
    for artist in fig.findobj(match=Text):
        artist.set_text(label(artist.get_text()))
    if name in ('图09_主模型SHAP蜂群图_前十变量','图11_SHAP重要性重拟合稳定性'):
        for tick in fig.axes[0].get_yticklabels():tick.set_text(wrapped_feature(tick.get_text()))
        # Setting ticks explicitly keeps the wrapped labels after a canvas draw.
        ax=fig.axes[0]
        ax.set_yticks(ax.get_yticks(),[wrapped_feature(t.get_text()) for t in ax.get_yticklabels()])
    if name=='图02_心理维度Spearman相关热图':
        fig.set_size_inches(14,12)
        fig.tight_layout()
    elif name=='图09_主模型SHAP蜂群图_前十变量':
        fig.set_size_inches(8.6,5.9)
        fig.axes[0].set_position([.37,.13,.50,.81])
        fig.axes[0].tick_params(axis='y',labelsize=9)
        fig.axes[1].set_position([.905,.19,.022,.68])
    elif name=='图11_SHAP重要性重拟合稳定性':
        fig.set_size_inches(8.8,5.8)
        fig.axes[0].set_position([.37,.14,.59,.75])
        fig.axes[0].tick_params(axis='y',labelsize=9)
    elif name=='图07_主模型概率校准曲线':
        fig.set_size_inches(6.8,5.5)
        fig.tight_layout(rect=(0,.045,1,1))
    elif name=='图08_主模型混淆矩阵':
        fig.set_size_inches(12,4.8)
        fig.axes[0].set_position([.10,.18,.32,.70])
        fig.axes[1].set_position([.53,.18,.32,.70])
        fig.axes[2].set_position([.91,.20,.015,.64])
    elif name not in ('图01_数据纳入与实验流程','图10_主模型SHAP瀑布图_前五变量'):
        fig.tight_layout()
    fig.canvas.draw()
    texts=[a.get_text() for a in fig.findobj(match=Text) if a.get_text()]
    remaining=[t for t in texts if CJK.search(t)]
    assert not remaining,remaining
    targets=[] if name.startswith('Figure_') else [Path(output)/'figures'/FIGURE_NAMES.get(name,name)]
    if name in MANUSCRIPT_NAMES:targets.append(Path(output)/'figures'/'manuscript'/MANUSCRIPT_NAMES[name])
    if extra_path:targets.append(Path(extra_path))
    for target in targets:
        target.parent.mkdir(parents=True,exist_ok=True)
        fig.savefig(target.with_suffix('.pdf'),dpi=600,bbox_inches='tight',pad_inches=.08)
        fig.savefig(target.with_suffix('.png'),dpi=600,bbox_inches='tight',pad_inches=.08)
    text_audit[FIGURE_NAMES.get(name,name)]=texts
    plt.close(fig)

